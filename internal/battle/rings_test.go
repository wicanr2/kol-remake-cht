func TestRingCellsMatchOriginal(t *testing.T) {
	for ring := 0; ring < RingCount; ring++ {
		got := RingCells(ring)
		want := originalRings[ring]
		if len(got) != len(want) {
			t.Fatalf("環 %d 有 %d 格，原版是 %d 格", ring, len(got), len(want))
		}
		if RingSize(ring) != len(want) {
			t.Fatalf("環 %d 的 RingSize 是 %d，原版是 %d", ring, RingSize(ring), len(want))
		}
		for i := range want {
			if got[i] != want[i] {
				t.Fatalf("環 %d 第 %d 格是 %v，原版是 %v", ring, i, got[i], want[i])
			}
		}
	}
}
