package world

import "image/color"

// 隊伍在野外是一個 2×2 的閃爍點。它不是畫成白色，而是把底下那四個像素的
// EGA 索引**與 15 互斥或**（RE-068）：原版畫格量到 0 → 15、8 → 7，
// 那正是 `index ^ 15`，也是 OR 15 解釋不了的那一組。
var egaPalette = [16]color.RGBA{
	{0x00, 0x00, 0x00, 0xFF}, {0x00, 0x00, 0xAA, 0xFF},
	{0x00, 0xAA, 0x00, 0xFF}, {0x00, 0xAA, 0xAA, 0xFF},
	{0xAA, 0x00, 0x00, 0xFF}, {0xAA, 0x00, 0xAA, 0xFF},
	{0xAA, 0x55, 0x00, 0xFF}, {0xAA, 0xAA, 0xAA, 0xFF},
	{0x55, 0x55, 0x55, 0xFF}, {0x55, 0x55, 0xFF, 0xFF},
	{0x55, 0xFF, 0x55, 0xFF}, {0x55, 0xFF, 0xFF, 0xFF},
	{0xFF, 0x55, 0x55, 0xFF}, {0xFF, 0x55, 0xFF, 0xFF},
	{0xFF, 0xFF, 0x55, 0xFF}, {0xFF, 0xFF, 0xFF, 0xFF},
}

// EGAIndex 回傳一個 EGA 顏色的索引；不是 EGA 色就回 −1。
func EGAIndex(c color.RGBA) int {
	for i, p := range egaPalette {
		if p.R == c.R && p.G == c.G && p.B == c.B {
			return i
		}
	}
	return -1
}

// InvertEGA 回傳索引與 15 互斥或之後的顏色；不是 EGA 色就原樣回傳。
func InvertEGA(c color.RGBA) color.RGBA {
	i := EGAIndex(c)
	if i < 0 {
		return c
	}
	return egaPalette[i^0x0F]
}
